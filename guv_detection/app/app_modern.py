class CalibrationWindow:
    """Modal window: click 2 points, enter real distance (um) -> returns mu_per_pixel"""
    def __init__(self, parent, image_path, image_name, default_mu):
        self.top = tk.Toplevel(parent)
        self.top.title(f"Calibrate — {image_name}")
        self.top.configure(bg=C["bg"])
        self.top.minsize(1175, 900)
        self.top.grab_set()  # modal
        self.parent = parent
        self.fam, self.mono = _fonts()

        self.image_path = image_path
        self.image_name = image_name
        self.points = []
        self.pixel_distance = 0.0
        self.mu_per_pixel = None
        self.calibration_done = False
        self.default_mu = default_mu

        # load image and scale if large
        self.original_image = Image.open(image_path)
        self.display_image = self.original_image.copy()
        max_display = 800
        if max(self.display_image.size) > max_display:
            ratio = max_display / max(self.display_image.size)
            new_size = (int(self.display_image.size[0] * ratio),
                        int(self.display_image.size[1] * ratio))
            self.display_image = self.display_image.resize(new_size, Image.LANCZOS)
            self.scale_factor = ratio
        else:
            self.scale_factor = 1.0

        self._build_ui()
        self._center()

    def _center(self):
        self.top.update_idletasks()
        w, h = 1400, 1075  # same size as the main window at opening
        x = (self.top.winfo_screenwidth() - w) // 2
        y = max((self.top.winfo_screenheight() - h) // 2 - 20, 0)
        self.top.geometry(f"{w}x{h}+{x}+{y}")

    def _build_ui(self):
        header = ttk.Frame(self.top, style="Head.TFrame", padding=(22, 16))
        header.pack(fill=tk.X)
        ttk.Label(header, text="Calibration", style="Title.TLabel",
                  font=(self.fam, 15, "bold")).pack(anchor=tk.W)
        ttk.Label(header, text=self.image_name, style="Sub.TLabel").pack(anchor=tk.W)

        body = ttk.Frame(self.top, padding=18)
        body.pack(fill=tk.BOTH, expand=True)
        body.columnconfigure(0, weight=1)
        body.rowconfigure(1, weight=1)

        steps = card(body, padding=14)
        steps.grid(row=0, column=0, sticky="ew")
        ttk.Label(steps.inner,
                  text="Click TWO points on the image to define a known distance",
                  style="CalTitle.TLabel").pack(anchor=tk.W)
        ttk.Label(steps.inner,
                  text="Then enter the REAL distance in um and press Calculate",
                  style="Hint.TLabel").pack(anchor=tk.W, pady=(3, 0))

        canvas_card = card(body, padding=10)
        canvas_card.grid(row=1, column=0, sticky="nsew", pady=(12, 12))
        holder = ttk.Frame(canvas_card.inner, style="Card.TFrame")
        holder.pack(expand=True)
        self.canvas = tk.Canvas(holder, width=self.display_image.width,
                                height=self.display_image.height, cursor="crosshair",
                                bg=C["surface_alt"], highlightthickness=1,
                                highlightbackground=C["border_strong"], bd=0)
        self.canvas.pack()
        self.photo = ImageTk.PhotoImage(self.display_image)
        self.canvas.create_image(0, 0, anchor=tk.NW, image=self.photo)
        self.canvas.bind("<Button-1>", self.on_click)

        controls = card(body, padding=16)
        controls.grid(row=2, column=0, sticky="ew")
        cin = controls.inner
        cin.columnconfigure(1, weight=1)

        self.info_label = ttk.Label(cin, text="Click FIRST point…", style="CalInfo.TLabel")
        self.info_label.grid(row=0, column=0, columnspan=3, sticky=tk.W, pady=(0, 12))

        ttk.Label(cin, text="Real distance (um)", style="Field.TLabel").grid(
            row=1, column=0, sticky=tk.W, padx=(0, 10))
        self.distance_entry = ttk.Entry(cin, width=14, font=(self.fam, 11))
        self.distance_entry.grid(row=1, column=1, sticky=tk.W)
        self.distance_entry.config(state="disabled")

        btn_frame = ttk.Frame(cin, style="Card.TFrame")
        btn_frame.grid(row=2, column=0, columnspan=3, sticky="ew", pady=(16, 0))
        ttk.Button(btn_frame, text="Reset points", style="Ghost.TButton",
                   command=self.reset_points).pack(side=tk.LEFT)
        ttk.Button(btn_frame, text=f"Skip (default {self.default_mu.get()})",
                   style="Ghost.TButton",
                   command=self.skip_calibration).pack(side=tk.LEFT, padx=8)
        ttk.Button(btn_frame, text="Calculate", style="Ghost.TButton",
                   command=self.calculate_calibration).pack(side=tk.LEFT)
        self.done_button = ttk.Button(btn_frame, text="Done", style="Primary.TButton",
                                      command=self.confirm_calibration)
        self.done_button.pack(side=tk.RIGHT)
        self.done_button.config(state="disabled")

    def on_click(self, event):
        if len(self.points) >= 2:
            messagebox.showinfo("Info", "Two points already selected. Reset to pick new points.")
            return
        x, y = event.x, event.y
        self.points.append((x, y))
        r = 5
        self.canvas.create_oval(x-r, y-r, x+r, y+r,
                                fill=C["primary"], outline="#FFFFFF", width=2, tags="cal")
        self.canvas.create_text(x, y-16, text=f"P{len(self.points)}", fill=C["primary_dark"],
                                font=(self.fam, 10, "bold"), tags="cal")
        if len(self.points) == 1:
            self.info_label.config(text="Click SECOND point…", foreground=C["primary_dark"])
        else:
            x0, y0 = self.points[0]
            x1, y1 = self.points[1]
            self.canvas.create_line(x0, y0, x1, y1, fill=C["primary"], width=3, tags="cal")
            dx = (x1 - x0) / self.scale_factor
            dy = (y1 - y0) / self.scale_factor
            self.pixel_distance = math.hypot(dx, dy)
            self.info_label.config(
                text=f"Pixel distance: {self.pixel_distance:.1f} px  ·  "
                     f"enter the real distance and press Calculate",
                foreground=C["deep"])
            self.distance_entry.config(state="normal")
            self.distance_entry.focus()

    def calculate_calibration(self):
        if len(self.points) < 2:
            messagebox.showwarning("Warning", "Select two points first.")
            return
        try:
            real_distance = float(self.distance_entry.get())
            if real_distance <= 0:
                raise ValueError("Distance must be > 0")
            self.mu_per_pixel = real_distance / self.pixel_distance
            self.info_label.config(
                text=f"Calibration: {self.mu_per_pixel:.4f} um/pixel",
                foreground=C["deep"])
            self.done_button.config(state="normal")
        except Exception as e:
            messagebox.showerror("Error", f"Invalid distance: {e}")

    def reset_points(self):
        self.points = []
        self.pixel_distance = 0.0
        self.mu_per_pixel = None
        self.canvas.delete("cal")
        self.info_label.config(text="Click FIRST point…", foreground=C["primary_dark"])
        self.distance_entry.delete(0, tk.END)
        self.distance_entry.config(state="disabled")
        self.done_button.config(state="disabled")

    def skip_calibration(self):
        if messagebox.askyesno("Skip calibration",
                               f"Skip calibration for {self.image_name}?\nDefault will be used."):
            self.mu_per_pixel = self.default_mu.get()
            self.done_button.config(state="normal")
            self.calibration_done = True
            self.top.destroy()

    def confirm_calibration(self):
        if self.mu_per_pixel is None:
            messagebox.showwarning("Warning", "Calculate or skip before confirming.")
            return
        self.calibration_done = True
        self.top.destroy()

    def get_calibration(self):
        self.top.wait_window()
        return self.mu_per_pixel if self.calibration_done else None


