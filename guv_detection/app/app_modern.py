def _fonts():
    fam = "Segoe UI"
    available = set(tkfont.families())
    for cand in ("Segoe UI", "Helvetica Neue", "Helvetica", "DejaVu Sans"):
        if cand in available:
            fam = cand
            break
    mono = "Consolas"
    for cand in ("Consolas", "Menlo", "DejaVu Sans Mono", "Courier New"):
        if cand in available:
            mono = cand
            break
    return fam, mono


