def card(parent, **kw):
    """A white surface with a 1px rose hairline border."""
    outer = tk.Frame(parent, bg=C["border"], bd=0, highlightthickness=0)
    inner = ttk.Frame(outer, style="Card.TFrame", padding=kw.pop("padding", 18))
    inner.pack(fill=tk.BOTH, expand=True, padx=1, pady=1)
    outer.inner = inner
    return outer


INDICATOR_SIZE = 24  # px — indicator size is independent of label font size


class RoseRadio:
    """Radio control drawn on a Canvas: a big circle in the dark rosa antico
    tone, sized independently of the label text next to it."""
    def __init__(self, parent, text, variable, value, bg=None):
        self.variable = variable
        self.value = value
        bg = bg or C["surface"]
        self.frame = ttk.Frame(parent, style="Card.TFrame")
        s = INDICATOR_SIZE
        pad = 3
        self.canvas = tk.Canvas(self.frame, width=s, height=s, bg=bg,
                                highlightthickness=0, cursor="hand2")
        self.canvas.pack(side=tk.LEFT, padx=(0, 8))
        self.ring = self.canvas.create_oval(pad, pad, s - pad, s - pad,
                                            outline=C["border_strong"], width=2,
                                            fill=C["surface_alt"])
        d0, d1 = s * 0.30, s * 0.70
        self.dot = self.canvas.create_oval(d0, d0, d1, d1, outline="", fill="")
        self.label = ttk.Label(self.frame, text=text, style="Card.TLabel", cursor="hand2")
        self.label.pack(side=tk.LEFT)
        for w in (self.canvas, self.label):
            w.bind("<Button-1>", self._select)
        self._trace_id = variable.trace_add("write", lambda *_: self._refresh())
        self._refresh()

    def _select(self, _event=None):
        self.variable.set(self.value)

    def _refresh(self):
        if self.variable.get() == self.value:
            self.canvas.itemconfig(self.ring, outline=C["primary_dark"])
            self.canvas.itemconfig(self.dot, fill=C["primary_dark"])
        else:
            self.canvas.itemconfig(self.ring, outline=C["border_strong"])
            self.canvas.itemconfig(self.dot, fill="")

    def pack(self, **kw):
        self.frame.pack(**kw)
        return self

    def grid(self, **kw):
        self.frame.grid(**kw)
        return self


