def resource_path(relative_path):
    if hasattr(sys, "_MEIPASS"):
        return os.path.join(sys._MEIPASS, relative_path)
    return os.path.join(os.path.abspath("."), relative_path)


# Prefix used to identify auto-generated subfolders (to be excluded from batch scan)
PROCESSING_FOLDER_PREFIX = "processing_images"

# Extensions accepted for SOURCE images (crops are always re-saved as .png)
SOURCE_IMAGE_EXT = ('.png', '.jpg', '.jpeg', '.bmp', '.tif', '.tiff')


def is_generated_folder(name: str) -> bool:
    """Return True if a folder name was auto-generated by a previous run."""
    return name == PROCESSING_FOLDER_PREFIX or (
        name.startswith(PROCESSING_FOLDER_PREFIX + "_") and
        name[len(PROCESSING_FOLDER_PREFIX) + 1:].isdigit()
    )


